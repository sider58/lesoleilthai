"""Rebuild the local Latin/French WOFF2 fonts.

Install the optional asset tooling once: python -m pip install "fonttools[woff]"
Then run: python scripts/prepare-fonts.py
The generated files are committed; normal Next.js builds do not need Python.
"""

from hashlib import sha256
from io import BytesIO
import json
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont


ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "assets" / "original-fonts"
OUTPUT = ROOT / "public" / "fonts"
CSS = ROOT / "app" / "fonts.css"
FONTS = [
    ("taviraj-600-normal", "Taviraj", 600, "normal"),
    ("taviraj-400-italic", "Taviraj", 400, "italic"),
    ("taviraj-700-italic", "Taviraj", 700, "italic"),
    ("gotu-400-normal", "Gotu", 400, "normal"),
    ("sarabun-400-normal", "Sarabun", 400, "normal"),
    ("sarabun-700-normal", "Sarabun", 700, "normal"),
    ("sarabun-800-normal", "Sarabun", 800, "normal"),
    ("golos-text-800-normal", "Golos Text", 800, "normal"),
    ("prompt-600-normal", "Prompt", 600, "normal"),
]
# Accents, ligatures, combining marks, punctuation, euro and arrows are kept.
# Keep ranges broader than the current copy so later French edits need no rebuild.
RANGES = [
    (0x0000, 0x024F),
    (0x0300, 0x036F),
    (0x1E00, 0x1EFF),
    (0x2000, 0x206F),
    (0x20A0, 0x20CF),
    (0x2122, 0x2122),
    (0x2190, 0x21FF),
    (0xFEFF, 0xFEFF),
    (0xFFFD, 0xFFFD),
]
UNICODES = {codepoint for start, end in RANGES for codepoint in range(start, end + 1)}


def main():
    OUTPUT.mkdir(parents=True, exist_ok=True)
    rules = ["/* Generated by scripts/prepare-fonts.py; edit the originals and regenerate. */"]
    report = []
    generated = set()

    for stem, family, weight, style in FONTS:
        source = SOURCE / f"{stem}.ttf"
        font = TTFont(source, recalcTimestamp=False)
        expected = set(font.getBestCmap()) & UNICODES
        options = subset.Options()
        options.flavor = "woff2"
        options.recalc_timestamp = False
        options.layout_features = ["*"]
        options.layout_scripts = ["latn", "DFLT"]
        options.legacy_kern = True
        options.notdef_glyph = True
        options.notdef_outline = True
        # Preserve font metadata, including copyright and licensing records.
        options.name_IDs = ["*"]
        options.name_languages = ["*"]
        options.name_legacy = True
        subsetter = subset.Subsetter(options=options)
        subsetter.populate(unicodes=UNICODES)
        subsetter.subset(font)
        font.flavor = "woff2"
        buffer = BytesIO()
        font.save(buffer)
        data = buffer.getvalue()
        # Verify all selected characters supported by the original survive.
        rebuilt = TTFont(BytesIO(data))
        missing = expected - set(rebuilt.getBestCmap())
        if missing:
            raise ValueError(f"Missing glyphs for {stem}: {sorted(missing)}")
        filename = f"{stem}.{sha256(data).hexdigest()[:12]}.woff2"
        (OUTPUT / filename).write_bytes(data)
        generated.add(filename)
        rules.append(
            f'@font-face {{ font-family: "{family}"; '
            f'src: url("/fonts/{filename}") format("woff2"); '
            f"font-style: {style}; font-weight: {weight}; font-display: swap; }}"
        )
        report.append({"font": stem, "originalBytes": source.stat().st_size, "woff2Bytes": len(data)})

    CSS.write_text("\n".join(rules) + "\n", encoding="utf-8")
    # Only remove old generated variants of these nine fonts, inside OUTPUT.
    for stem, *_ in FONTS:
        for old in OUTPUT.glob(f"{stem}.*.woff2"):
            if old.name not in generated:
                old.unlink()
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
